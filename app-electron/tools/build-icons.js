// Regenerates src/icons.js from the Solar icon set (CC BY 4.0) and the Modrinth logo (simple-icons, CC0).
// Usage: npm run icons
// To add an icon: add a line to PICK (name used in the HTML as data-i="name" -> Solar icon id), then run the script.
// Browse icons at https://icon-sets.iconify.design/solar/ - the style used everywhere is "bold-duotone".
const fs = require('fs');
const path = require('path');
const solar = require('@iconify-json/solar/icons.json');
const si = require('simple-icons');

const PICK = {
  home: 'home-2-bold-duotone', events: 'cup-first-bold-duotone', mods: 'box-bold-duotone',
  cosmetics: 'hanger-2-bold-duotone', settings: 'settings-bold-duotone', friends: 'users-group-rounded-bold-duotone',
  play: 'play-bold', down: 'alt-arrow-down-linear', right: 'alt-arrow-right-linear', download: 'download-minimalistic-bold',
  check: 'check-circle-bold', search: 'magnifer-bold-duotone', shield: 'shield-check-bold-duotone', verified: 'verified-check-bold',
  refresh: 'refresh-linear', heart: 'heart-bold', user: 'user-bold-duotone', logout: 'logout-2-bold-duotone',
  adduser: 'user-plus-rounded-bold-duotone', gamepad: 'gamepad-bold-duotone', plus: 'add-circle-bold-duotone', star: 'star-bold',
  share: 'share-bold-duotone', trash: 'trash-bin-trash-bold-duotone', fire: 'fire-bold-duotone', crown: 'crown-bold-duotone',
  clock: 'clock-circle-bold-duotone', danger: 'danger-circle-bold-duotone', layers: 'layers-bold-duotone', image: 'gallery-bold-duotone',
  code: 'code-square-bold-duotone', sun: 'sun-2-bold-duotone', cape: 't-shirt-bold-duotone', wings: 'wind-bold-duotone',
  hat: 'crown-minimalistic-bold-duotone', emote: 'emoji-funny-circle-bold-duotone', medal: 'medal-ribbons-star-bold-duotone',
  lock: 'lock-keyhole-bold-duotone', world: 'earth-bold-duotone',
  support: 'headphones-round-sound-bold-duotone', globe: 'global-bold-duotone',
  link: 'link-round-bold-duotone', left: 'alt-arrow-left-linear', out: 'arrow-right-up-linear',
  library: 'library-bold-duotone', store: 'bag-4-bold-duotone', clips: 'videocamera-record-bold-duotone', news: 'document-text-bold-duotone',
  servers: 'server-2-bold-duotone', copy: 'copy-bold-duotone', edit: 'pen-bold-duotone', folder: 'folder-open-bold-duotone',
};

const svg = ic => `<svg viewBox="0 0 ${ic.width || solar.width || 24} ${ic.height || solar.height || 24}" width="1em" height="1em" fill="none">${ic.body}</svg>`;
const out = {};
for (const [name, id] of Object.entries(PICK)) {
  if (!solar.icons[id]) throw new Error(`Solar icon not found: ${id} (for "${name}")`);
  out[name] = svg(solar.icons[id]);
}
out.discord = `<svg viewBox="0 0 24 24" width="1em" height="1em" fill="currentColor"><path d="${si.siDiscord.path}"/></svg>`;
out.modrinth = `<svg viewBox="0 0 24 24" width="1em" height="1em" fill="currentColor"><path d="${si.siModrinth.path}"/></svg>`;

const file = path.join(__dirname, '..', 'src', 'icons.js');
fs.writeFileSync(file, `// GENERATED by tools/build-icons.js. Do not edit by hand. Solar icons (CC BY 4.0), Modrinth logo (CC0).\nconst ICONS = ${JSON.stringify(out)};\n`);
console.log(`wrote ${Object.keys(out).length} icons to src/icons.js`);

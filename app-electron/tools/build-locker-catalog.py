#!/usr/bin/env python3
"""Collects the stack Dexter Client ships in the launcher: the animated cloaks and the emotes, into assets/locker/ +
assets/locker/catalog.json, so the Dexter UI can show them offline. Run: python3 tools/build-locker-catalog.py"""
import json, os, re, shutil

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(HERE)
SRC = os.path.join(os.path.dirname(APP), "source")
LAUNCHER_RES = os.path.join(SRC, "launcher/src/main/resources/net/veloclient/launcher")
CLIENT_RES = os.path.join(SRC, "src/client/resources/assets/velo-client")
OUT = os.path.join(APP, "assets", "locker")

pretty = lambda s: re.sub(r"[_-]+", " ", s).title()
cat = {}

# capes (the animated cloaks in the Locker)
for sub in ("capes",):
    shutil.rmtree(os.path.join(OUT, sub), ignore_errors=True)
    os.makedirs(os.path.join(OUT, sub), exist_ok=True)
capes = []
d = os.path.join(LAUNCHER_RES, "store/cape")
for f in sorted(os.listdir(d)):
    if f.endswith(".gif"):
        cid = f[:-4]; shutil.copy(os.path.join(d, f), os.path.join(OUT, "capes", f))
        capes.append({"id": cid, "name": pretty(cid.replace("cape_", "")), "img": f"capes/{f}"})
names = {"cape_black_pattern": "Digitized", "cape_red_code": "Codebreaker", "cape_red_lightning": "Storm Strike", "cape_symbols": "Rune Weave"}
for c in capes:
    c["name"] = names.get(c["id"], c["name"])
cat["capes"] = capes

# emotes
em = json.load(open(os.path.join(CLIENT_RES, "emotes/emotes.json")))["emotes"]
cat["emotes"] = [{"id": e["id"], "name": e["name"]} for e in em]

# 3D assets that no longer exist (wings/pets) - remove anything an older checkout left behind
for sub in ("wings", "wings3d", "pets", "pets3d", "killfx"):
    shutil.rmtree(os.path.join(OUT, sub), ignore_errors=True)

json.dump(cat, open(os.path.join(OUT, "catalog.json"), "w"), indent=1)
open(os.path.join(OUT, "catalog.js"), "w").write("// GENERATED by tools/build-locker-catalog.py\nconst LOCKER = " + json.dumps(cat) + ";\n")
print({k: len(v) for k, v in cat.items()})
